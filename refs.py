#!/usr/bin/python3
#показываем что не копирует
a=[1,2,3]
b=a #ссылаемся на один список
b.append(9)
print(a,b) #изменятся оба списка
print(a is b) #один и тот же объект
# показываем, что += создает новый объект
x=10
y=x
y+=5 #создаем новый объект y
print(x,y) #x остается, y меняется
print(x is y) # это разные объекты
# показываем,что == сравнивает значения, а is идентичность
l1=[1, 2, 3]
l2=[1, 2, 3]
print(l1==l2) # значения равны
print(l1 is l2) # разные объекты в памяти

